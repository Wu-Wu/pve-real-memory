// Package patch manages the pve-real-memory hook inside
// /usr/share/perl5/PVE/QemuServer.pm. The hook replaces the "mem" field of
// vmstatus() results with values written by the daemon, as long as the
// override file is fresh.
//
// Design notes (from the audit of the Python predecessor):
//   - The generated block is bounded by BEGIN/END markers, so removal is
//     exact text surgery without brace counting — uninstall never restores
//     a stale .bak and can never downgrade QemuServer.pm after an upgrade.
//   - The inserted Perl checks file freshness (-M), so unreachable guests
//     expire back to the host view instead of freezing stale values forever.
//   - Insertion anchors on "$qmpclient->queue_execute(undef, 2);" (present
//     and unique in qemu-server 9.0..9.3) and falls back to the last
//     "return $res;" of sub vmstatus.
//   - Every apply is verified with perl -c and auto-reverted on failure.
package patch

import (
	"errors"
	"fmt"
	"os"
	"regexp"
	"strings"
)

const (
	// BeginMarker and EndMarker bound our generated block.
	BeginMarker = "# BEGIN pve-real-memory override (generated by pve-real-memory; remove via --uninstall)"
	EndMarker   = "# END pve-real-memory override"

	// anchorPrimary is the QMP fan-out call at the end of vmstatus().
	anchorPrimary = "$qmpclient->queue_execute(undef, 2);"
)

// LegacyMarker is the marker comment written by the old proxmox-rmem
// project (both its old and new patch shapes start with it and contain no
// blank lines before the first empty line closes the block).
const LegacyMarker = "proxmox-rmem: Override memory from external file if available"

var (
	// returnResRe matches the closing "return $res;\n}" of sub vmstatus.
	returnResRe = regexp.MustCompile(`(?m)\n([ \t]*)return \$res;\n\}`)

	// legacyBlockRe removes the old proxmox-rmem block: marker comment
	// through the first blank line after it. Generated by both known patch
	// shapes of the old project.
	legacyBlockRe = regexp.MustCompile(`(?s)\n[ \t]*#[^\n]*` + regexp.QuoteMeta(LegacyMarker) + `[^\n]*\n.*?\n\n`)

	// ourBlockRe removes our own block precisely between markers.
	ourBlockRe = regexp.MustCompile(`(?s)\n[ \t]*` + regexp.QuoteMeta(BeginMarker) + `\n.*?` + regexp.QuoteMeta(EndMarker) + `\n\n?`)

	// subVMStatusRe locates the vmstatus sub (fallback insertion).
	subVMStatusRe = regexp.MustCompile(`(?m)^sub vmstatus \{`)
)

// blockTemplate is the Perl code inserted before vmstatus()'s return.
// %[1]s is the base indent, %[2]d the freshness TTL in seconds.
const blockTemplate = `
%[1]s%[3]s
%[1]s{
%[1]s    my $prm_ttl_days = %[2]d / 86400;
%[1]s    foreach my $prm_vmid (keys %%$res) {
%[1]s        my $prm_file = "%[4]s/$prm_vmid.mem";
%[1]s        next if ! -f $prm_file;
%[1]s        next if -M $prm_file > $prm_ttl_days;
%[1]s        if (open(my $prm_fh, '<', $prm_file)) {
%[1]s            my $prm_val = <$prm_fh>;
%[1]s            close($prm_fh);
%[1]s            if (defined $prm_val) {
%[1]s                chomp $prm_val;
%[1]s                $res->{$prm_vmid}->{mem} = $prm_val if $prm_val =~ /^\d+$/;
%[1]s            }
%[1]s        }
%[1]s    }
%[1]s}
%[1]s%[5]s
`

// Block renders the Perl hook at the given indent.
func Block(indent string, ttlSeconds int, overrideDir string) string {
	return fmt.Sprintf(blockTemplate, indent, ttlSeconds, BeginMarker, overrideDir, EndMarker)
}

// Status describes the current patch state of a QemuServer.pm file.
type Status int

const (
	// NotApplied means no pve-real-memory block was found.
	NotApplied Status = iota
	// Applied means our block is present.
	Applied
	// FileMissing means QemuServer.pm does not exist (not a PVE host?).
	FileMissing
)

func (s Status) String() string {
	switch s {
	case Applied:
		return "applied"
	case FileMissing:
		return "file-missing"
	default:
		return "not-applied"
	}
}

// Verifier compiles-checks the patched file at its real path. Production
// uses perl -c; tests inject a stub.
type Verifier func(path string) error

// Engine operates on one QemuServer.pm.
type Engine struct {
	Path        string
	OverrideDir string
	TTLSeconds  int
	Verifier    Verifier
	// BackupFunc is called with the original content right before a
	// successful write; used for backup bookkeeping.
	BackupFunc func(original []byte) error
}

// read returns the current file content.
func (e *Engine) read() ([]byte, error) {
	return os.ReadFile(e.Path)
}

// Status reports whether our hook is present.
func (e *Engine) Status() Status {
	raw, err := e.read()
	if err != nil {
		return FileMissing
	}
	if strings.Contains(string(raw), BeginMarker) {
		return Applied
	}
	return NotApplied
}

// LegacyPresent reports whether an old proxmox-rmem hook is present.
func (e *Engine) LegacyPresent() bool {
	raw, err := e.read()
	if err != nil {
		return false
	}
	return strings.Contains(string(raw), LegacyMarker)
}

// findInsertion locates (position, indent) just before vmstatus()'s final
// "return $res;\n}". The primary anchor pins us after QMP/balloon
// processing so our value wins; without the anchor we fall back to the last
// return inside sub vmstatus.
func findInsertion(content string) (pos int, indent string, fallback bool, err error) {
	idx := strings.Index(content, anchorPrimary)
	if idx == -1 {
		// Fallback: last "return $res;" within sub vmstatus.
		loc := subVMStatusRe.FindStringIndex(content)
		if loc == nil {
			return 0, "", false, errors.New("neither the QMP anchor nor 'sub vmstatus' found; refusing to patch an unexpected QemuServer.pm")
		}
		sub := content[loc[0]:]
		end := strings.Index(sub, "\n}\n")
		if end == -1 {
			return 0, "", false, errors.New("could not find the end of sub vmstatus")
		}
		sub = sub[:end+3]
		all := returnResRe.FindAllStringSubmatchIndex(sub, -1)
		if len(all) == 0 {
			return 0, "", false, errors.New("no 'return $res;' at end of sub vmstatus")
		}
		last := all[len(all)-1]
		fallback = true
		// indent group span: last[2]:last[3]
		indent = sub[last[2]:last[3]]
		return loc[0] + last[0] + 1, indent, fallback, nil
	}

	m := returnResRe.FindStringSubmatchIndex(content[idx:])
	if m == nil {
		return 0, "", false, errors.New("found the QMP anchor but no following 'return $res;' before the end of the block")
	}
	indent = content[idx+m[2] : idx+m[3]]
	return idx + m[0] + 1, indent, false, nil
}

// Apply installs the hook unless already present. It is idempotent,
// verifies the result and reverts on verification failure.
func (e *Engine) Apply() (applied bool, fallback bool, err error) {
	raw, err := e.read()
	if err != nil {
		return false, false, fmt.Errorf("read %s: %w", e.Path, err)
	}
	content := string(raw)
	if strings.Contains(content, BeginMarker) {
		return false, false, nil // already patched
	}

	pos, indent, fb, err := findInsertion(content)
	if err != nil {
		return false, false, err
	}

	block := Block(indent, e.TTLSeconds, e.OverrideDir)
	newContent := content[:pos] + block + content[pos:]

	if err := e.writeVerified([]byte(content), []byte(newContent)); err != nil {
		return false, false, err
	}
	return true, fb, nil
}

// Remove strips our block. It is pure text surgery: safe at any Proxmox
// version, never touches the rest of the file, idempotent.
func (e *Engine) Remove() (removed bool, err error) {
	raw, err := e.read()
	if err != nil {
		return false, fmt.Errorf("read %s: %w", e.Path, err)
	}
	content := string(raw)
	if !strings.Contains(content, BeginMarker) {
		return false, nil
	}
	newContent := ourBlockRe.ReplaceAllString(content, "")
	if newContent == content {
		return false, fmt.Errorf("marker present but block regex did not match; refusing to edit")
	}
	if strings.Contains(newContent, BeginMarker) || strings.Contains(newContent, EndMarker) {
		return false, fmt.Errorf("marker(s) still present after removal; refusing to write")
	}
	if err := e.writeVerified(raw, []byte(newContent)); err != nil {
		return false, err
	}
	return true, nil
}

// RemoveLegacy strips hooks left by the old proxmox-rmem project. It does
// not verify-compile (the remaining file must still compile; we do check
// with the injected verifier when available).
func (e *Engine) RemoveLegacy() (removed bool, err error) {
	raw, err := e.read()
	if err != nil {
		return false, err
	}
	content := string(raw)
	if !strings.Contains(content, LegacyMarker) {
		return false, nil
	}
	newContent := legacyBlockRe.ReplaceAllString(content, "")
	if newContent == content {
		return false, fmt.Errorf("legacy marker present but regex did not match; refusing to edit")
	}
	if strings.Contains(newContent, LegacyMarker) {
		return false, fmt.Errorf("legacy marker still present after removal; refusing to write")
	}
	if err := e.writeVerified(raw, []byte(newContent)); err != nil {
		return false, err
	}
	return true, nil
}

// writeVerified backs up the original, writes the new content, runs the
// verifier and restores the original when verification fails.
func (e *Engine) writeVerified(original, updated []byte) error {
	info, err := os.Stat(e.Path)
	if err != nil {
		return err
	}

	if e.BackupFunc != nil {
		if err := e.BackupFunc(original); err != nil {
			return fmt.Errorf("backup: %w", err)
		}
	}

	if err := writeAtomic(e.Path, updated, info.Mode()); err != nil {
		return fmt.Errorf("write: %w", err)
	}

	if e.Verifier != nil {
		if err := e.Verifier(e.Path); err != nil {
			// revert
			if rerr := writeAtomic(e.Path, original, info.Mode()); rerr != nil {
				return fmt.Errorf("verify failed (%v) and revert failed (%v): MANUAL CHECK REQUIRED", err, rerr)
			}
			return fmt.Errorf("patch rejected by syntax check: %w", err)
		}
	}
	return nil
}

// writeAtomic replaces a file via temp+rename, preserving the mode.
func writeAtomic(path string, content []byte, mode os.FileMode) error {
	tmp := path + ".prm-new"
	if err := os.WriteFile(tmp, content, mode); err != nil {
		return err
	}
	if err := os.Chmod(tmp, mode); err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, path)
}
